"""
Datasphere Export/Import Adapter (§8, §16).
Handles bidirectional conversion between Datasphere export zip bundles and DS ModelForge ViewSpecs.
Also formats CSN/JSON bundles for direct deployment into Datasphere spaces via Data Builder APIs.
"""
import io
import json
import logging
import zipfile
from typing import Any

from formatlib.v1_scaffold.renderer import render_datasphere_object

logger = logging.getLogger(__name__)


class DatasphereExportImportAdapter:
    """Adapter for compiling and unpacking Datasphere CSN / native export bundles."""

    def __init__(self, release: str = "2024.Q3"):
        self.release = release

    def compile_bundle(self, views: list[dict[str, Any]], space: str) -> bytes:
        """
        Compile an array of canonical ViewSpec dictionaries into a full Datasphere-native
        zip archive containing per-object JSONs, CSN definitions, manifest.json, and import guide.
        """
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
            manifest_objects = []
            all_filters = []

            # Layer sorting priority
            layer_priority = {"L1": 1, "L2": 2, "L3": 3, "L4": 4}
            sorted_views = sorted(
                views,
                key=lambda v: layer_priority.get(v.get("layer", "L1"), 2)
            )

            for view in sorted_views:
                view_name = view.get("objectId") or view.get("view_name") or "UNKNOWN_VIEW"
                kind = view.get("kind", "graphical_view")
                layer = view.get("layer", "L1")
                ds_json = render_datasphere_object(view, release=self.release)

                filename = f"objects/{view_name}.datasphere.json"
                zf.writestr(filename, json.dumps(ds_json, indent=2))

                # Export individual SQL scripts if available
                sql_query = view.get("sqlQuery") or view.get("sql")
                if sql_query:
                    sql_filename = f"sql_scripts/{view_name}.sql"
                    zf.writestr(sql_filename, sql_query)

                # Collect filters for explanation document
                filters = view.get("filters", [])
                for op in view.get("operators", []):
                    if op.get("op") == "filter" and op.get("expression"):
                        filters.append(op)
                if filters:
                    all_filters.append({"view": view_name, "filters": filters})

                manifest_objects.append({
                    "name": view_name,
                    "kind": kind,
                    "layer": layer,
                    "file": filename,
                    "business_name": view.get("businessName") or view.get("business_name"),
                    "dependencies": [s.get("object_name") or s.get("objectId") for s in view.get("sources", []) if s],
                })

            # Add filter_expressions.md
            if all_filters:
                filter_doc_lines = [
                    "# Datasphere Filter Expressions Reference",
                    f"Generated for Space: {space}\n",
                ]
                for item in all_filters:
                    filter_doc_lines.append(f"## View: `{item['view']}`")
                    for flt in item["filters"]:
                        if isinstance(flt, dict):
                            expr = flt.get("expression", "")
                            rat = flt.get("rationale", "")
                            filter_doc_lines.append(f"- **Expression**: `{expr}`")
                            if rat:
                                filter_doc_lines.append(f"  - *Rationale*: {rat}")
                        else:
                            filter_doc_lines.append(f"- **Expression**: `{flt}`")
                    filter_doc_lines.append("")
                zf.writestr("sql_scripts/filter_expressions.md", "\n".join(filter_doc_lines))

            # Add manifest.json
            manifest = {
                "generator": "DS ModelForge v1.0",
                "space": space,
                "ds_release": self.release,
                "objects": manifest_objects,
                "total_objects": len(manifest_objects),
            }
            zf.writestr("manifest.json", json.dumps(manifest, indent=2))

            # Add README / import instructions
            readme = f"""# SAP Datasphere Import Guide

Space: {space}
Generated by DS ModelForge v1.0

## Import Instructions
1. Log in to your SAP Datasphere tenant.
2. Select space '{space}'.
3. Navigate to Data Builder -> Import -> Import from File / CSN.
4. Select the objects in order of dependency:
   - Staging graphical views first (L1)
   - Joined & Dimension views second (L2 / L3)
   - SQL views (copy SQL from sql_scripts/ or import JSON)
   - Analytic models last (L4)
5. Deploy each object.
"""
            zf.writestr("README_IMPORT_GUIDE.md", readme)

        buf.seek(0)
        return buf.getvalue()

    def parse_bundle(self, bundle_bytes: bytes) -> list[dict[str, Any]]:
        """
        Unpack an existing Datasphere export zip file to extract ViewSpecs or definitions.
        """
        results = []
        with zipfile.ZipFile(io.BytesIO(bundle_bytes), "r") as zf:
            for name in zf.namelist():
                if name.endswith(".json") and not name.endswith("manifest.json"):
                    try:
                        content = json.loads(zf.read(name).decode("utf-8"))
                        results.append(content)
                    except Exception as e:
                        logger.warning("Could not parse %s from zip bundle: %s", name, e)
        return results
